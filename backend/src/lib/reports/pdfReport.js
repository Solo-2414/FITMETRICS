import PDFDocument from 'pdfkit';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { formatValue, formatDateTime, isNumericType } from './format.js';

const FONT_DIR = join(dirname(fileURLToPath(import.meta.url)), 'fonts');
const C = {
  navy: '#1e293b', ink: '#0f172a', muted: '#64748b', line: '#e2e8f0', zebra: '#f8fafc',
  card: '#f1f5f9', accent: '#38bdf8', accentDark: '#0284c7', totals: '#e0f2fe', white: '#ffffff',
};
const M = 40;              // page margin
const HEADER_BOTTOM = 66;  // where page content starts (below the running header)
const FOOTER_RESERVE = 56; // space kept free for the footer
const PAD = 8, ROW_H = 22, HEAD_H = 26, FONT = 8.5;

/**
 * spec = {
 *   gymName, title, period, generatedBy, generatedAt,
 *   summary: [{ label, value, type }]  (max 4 cards),
 *   columns: [{ key, label, type: 'text'|'int'|'money'|'number'|'percent'|'date'|'time'|'datetime' }],
 *   rows: [{...}], totals: { label, values: { [key]: number } } | null,
 *   orientation: 'portrait' | 'landscape' (default: landscape when more than 6 columns)
 * }
 * Returns a Promise<Buffer> (A4).
 */
export function buildReportPdf(spec) {
  return new Promise((resolve, reject) => {
    const {
      gymName = "Analyn's Fitness Gym", title, period = '', generatedBy = 'FITMETRICS',
      generatedAt = new Date(), summary = [], columns, rows = [], totals = null,
    } = spec;

    const landscape = spec.orientation ? spec.orientation === 'landscape' : columns.length > 6;
    const doc = new PDFDocument({
      size: 'A4', layout: landscape ? 'landscape' : 'portrait',
      margins: { top: M, bottom: FOOTER_RESERVE, left: M, right: M },
      bufferPages: true,
      info: { Title: title, Author: gymName, Creator: 'FITMETRICS' },
    });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.registerFont('Regular', join(FONT_DIR, 'Inter-Regular.ttf'));
    doc.registerFont('Bold', join(FONT_DIR, 'Inter-Bold.ttf'));

    const contentW = doc.page.width - 2 * M;
    const pageBottom = () => doc.page.height - FOOTER_RESERVE;

    // Truncate with an ellipsis so text never spills into the next column.
    const fit = (text, width, font = 'Regular', size = FONT) => {
      doc.font(font).fontSize(size);
      const s = String(text);
      if (doc.widthOfString(s) <= width) return s;
      let lo = 0, hi = s.length;
      while (lo < hi) {
        const mid = Math.ceil((lo + hi) / 2);
        if (doc.widthOfString(`${s.slice(0, mid)}…`) <= width) lo = mid; else hi = mid - 1;
      }
      return `${s.slice(0, lo).trimEnd()}…`;
    };

    // Running header on every page
    const drawHeader = () => {
      doc.font('Bold').fontSize(13).fillColor(C.navy).text(gymName, M, M, { lineBreak: false });
      doc.font('Bold').fontSize(10).fillColor(C.accentDark)
        .text('FITMETRICS', M, M + 3, { width: contentW, align: 'right', lineBreak: false });
      doc.moveTo(M, HEADER_BOTTOM - 8).lineTo(M + contentW, HEADER_BOTTOM - 8).lineWidth(1.5).strokeColor(C.accent).stroke();
    };
    drawHeader();
    doc.on('pageAdded', drawHeader);

    // Title block (first page)
    let y = HEADER_BOTTOM + 8;
    doc.font('Bold').fontSize(20).fillColor(C.ink).text(title, M, y, { width: contentW });
    y = doc.y + 3;
    if (period) {
      doc.font('Regular').fontSize(10.5).fillColor(C.muted).text(period, M, y, { width: contentW });
      y = doc.y + 2;
    }
    doc.font('Regular').fontSize(8.5).fillColor(C.muted)
      .text(`Generated by ${generatedBy}  ·  ${formatDateTime(generatedAt)}`, M, y, { width: contentW });
    y = doc.y + 16;

    // Summary cards
    const cards = summary.slice(0, 4);
    if (cards.length) {
      const gap = 10, w = (contentW - gap * (cards.length - 1)) / cards.length, h = 50;
      cards.forEach((s, i) => {
        const x = M + i * (w + gap);
        doc.roundedRect(x, y, w, h, 6).fill(C.card);
        doc.rect(x, y + 9, 3, h - 18).fill(C.accent);
        doc.font('Regular').fontSize(8).fillColor(C.muted).text(fit(s.label, w - 24, 'Regular', 8), x + 14, y + 10, { lineBreak: false });
        doc.font('Bold').fontSize(14).fillColor(C.navy)
          .text(fit(formatValue(s.type || 'text', s.value), w - 24, 'Bold', 14), x + 14, y + 24, { lineBreak: false });
      });
      y += h + 18;
    }

    // Column widths: fit content, then stretch to the page width (long text columns give way first)
    doc.font('Regular').fontSize(FONT);
    const natural = columns.map((col) => {
      doc.font('Bold').fontSize(FONT);
      let max = doc.widthOfString(col.label);
      doc.font('Regular').fontSize(FONT);
      for (const row of rows.slice(0, 300)) max = Math.max(max, doc.widthOfString(formatValue(col.type, row[col.key])));
      if (totals) {
        doc.font('Bold').fontSize(FONT);
        max = Math.max(max, doc.widthOfString(formatValue(col.type, totals.values?.[col.key])));
        doc.font('Regular').fontSize(FONT);
      }
      return max + 2 * PAD + 2;
    });
    const textIdx = columns.map((c, i) => (!isNumericType(c.type) && !['date', 'time', 'datetime'].includes(c.type) ? i : -1)).filter((i) => i >= 0);
    const widths = [...natural];
    const total = widths.reduce((a, b) => a + b, 0);
    if (total < contentW) {
      const growIdx = textIdx.length ? textIdx : columns.map((_, i) => i);
      const growBase = growIdx.reduce((a, i) => a + natural[i], 0);
      growIdx.forEach((i) => { widths[i] += ((contentW - total) * natural[i]) / growBase; });
    } else if (total > contentW) {
      const minFor = (i) => Math.min(natural[i], 80);
      const shrinkable = textIdx.reduce((a, i) => a + (natural[i] - minFor(i)), 0);
      const over = total - contentW;
      if (shrinkable >= over) textIdx.forEach((i) => { widths[i] -= (over * (natural[i] - minFor(i))) / shrinkable; });
      else { const k = contentW / total; widths.forEach((_, i) => { widths[i] = natural[i] * k; }); }
    }
    const xs = widths.map((_, i) => M + widths.slice(0, i).reduce((a, b) => a + b, 0));
    const align = (col) => (isNumericType(col.type) ? 'right' : 'left');

    const cellText = (text, x, ty, w, alignment, font, color) => {
      const s = fit(text, w, font);
      doc.font(font).fontSize(FONT).fillColor(color);
      const tx = alignment === 'right' ? x + w - doc.widthOfString(s) : x;
      doc.text(s, tx, ty, { lineBreak: false });
    };

    const drawTableHead = () => {
      doc.rect(M, y, contentW, HEAD_H).fill(C.navy);
      columns.forEach((col, i) => {
        cellText(col.label, xs[i] + PAD, y + (HEAD_H - FONT) / 2 - 1, widths[i] - 2 * PAD, align(col), 'Bold', C.white);
      });
      y += HEAD_H;
    };
    const ensureSpace = (h) => {
      if (y + h > pageBottom()) { doc.addPage(); y = HEADER_BOTTOM + 8; drawTableHead(); }
    };
    const drawRow = (values, { bold = false, fill = null, topLine = false }) => {
      ensureSpace(ROW_H);
      if (fill) doc.rect(M, y, contentW, ROW_H).fill(fill);
      columns.forEach((col, i) => {
        const font = bold ? 'Bold' : 'Regular';
        cellText(values[i], xs[i] + PAD, y + (ROW_H - FONT) / 2 - 1, widths[i] - 2 * PAD, align(col), font, bold ? C.navy : C.ink);
      });
      doc.moveTo(M, y + ROW_H).lineTo(M + contentW, y + ROW_H).lineWidth(topLine ? 0 : 0.5).strokeColor(C.line).stroke();
      if (topLine) doc.moveTo(M, y).lineTo(M + contentW, y).lineWidth(1).strokeColor(C.navy).stroke();
      y += ROW_H;
    };

    drawTableHead();
    if (!rows.length) {
      doc.roundedRect(M, y + 10, contentW, 56, 6).fill(C.card);
      doc.font('Regular').fontSize(10).fillColor(C.muted)
        .text('No records for this period.', M, y + 33, { width: contentW, align: 'center', lineBreak: false });
      y += 76;
    } else {
      rows.forEach((row, idx) => {
        if (totals && idx === rows.length - 1) ensureSpace(ROW_H * 2 + 30); // keep the last row with the totals
        drawRow(columns.map((c) => formatValue(c.type, row[c.key])), { fill: idx % 2 === 1 ? C.zebra : null });
      });
      if (totals) {
        drawRow(columns.map((c, i) => (totals.values?.[c.key] !== undefined ? formatValue(c.type, totals.values[c.key]) : i === 0 ? totals.label || 'Total' : '')),
          { bold: true, fill: C.totals, topLine: true });
      }
      ensureSpace(24);
      doc.font('Regular').fontSize(8).fillColor(C.muted)
        .text(`${rows.length} record${rows.length === 1 ? '' : 's'}`, M, y + 8, { lineBreak: false });
    }

    // Footer on every page: gym name left, "Page X of Y" right
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.page.margins.bottom = 0; // allow drawing inside the reserved footer space without adding a page
      const fy = doc.page.height - 34;
      doc.moveTo(M, fy - 7).lineTo(M + contentW, fy - 7).lineWidth(0.5).strokeColor(C.line).stroke();
      doc.font('Regular').fontSize(7.5).fillColor(C.muted).text(`${gymName}  ·  FITMETRICS`, M, fy, { lineBreak: false });
      doc.text(`Page ${i + 1} of ${range.count}`, M, fy, { width: contentW, align: 'right', lineBreak: false });
    }
    doc.end();
  });
}
