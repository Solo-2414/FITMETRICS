import ExcelJS from 'exceljs';
import { formatDateTime, formatPeriod, toDate, toManilaWallClock, isNumericType } from './format.js';

const NAVY = 'FF1E293B', ZEBRA = 'FFF8FAFC', LINE = 'FFE2E8F0', TOTALS = 'FFE0F2FE', MUTED = 'FF64748B', ACCENT = 'FF0284C7';
const NUM_FMT = {
  money: '"₱"#,##0.00', int: '#,##0', number: '#,##0.0', percent: '0.0%',
  date: 'mmm d, yyyy', time: 'h:mm AM/PM', datetime: 'mmm d, yyyy h:mm AM/PM',
};

/** Same `spec` as buildReportPdf. Returns a Promise<Buffer> (.xlsx) with real dates and numbers. */
export async function buildReportXlsx(spec) {
  const {
    gymName = "Analyn's Fitness Gym", title, period = '', generatedBy = 'FITMETRICS',
    generatedAt = new Date(), summary = [], columns, rows = [], totals = null,
  } = spec;

  const wb = new ExcelJS.Workbook();
  wb.creator = 'FITMETRICS';
  wb.created = new Date();
  const sheetName = title.replace(/[\\/?*[\]:]/g, '').slice(0, 31) || 'Report';
  const landscape = spec.orientation ? spec.orientation === 'landscape' : columns.length > 6;
  const ws = wb.addWorksheet(sheetName, {
    pageSetup: {
      paperSize: 9, orientation: landscape ? 'landscape' : 'portrait', fitToPage: true, fitToWidth: 1, fitToHeight: 0,
      margins: { left: 0.5, right: 0.5, top: 0.6, bottom: 0.7, header: 0.3, footer: 0.3 },
    },
    headerFooter: { oddFooter: `&L&8${gymName.replace(/&/g, '&&')} · FITMETRICS&R&8Page &P of &N` },
    views: [{ showGridLines: false }],
  });
  const last = columns.length;

  // ---- Title block
  const put = (row, text, font, height) => {
    ws.mergeCells(row, 1, row, Math.max(last, 2));
    const c = ws.getCell(row, 1);
    c.value = text; c.font = font; c.alignment = { vertical: 'middle', horizontal: 'left' };
    if (height) ws.getRow(row).height = height;
  };
  put(1, gymName, { name: 'Calibri', size: 16, bold: true, color: { argb: NAVY } }, 26);
  put(2, title, { name: 'Calibri', size: 13, bold: true, color: { argb: ACCENT } }, 20);
  put(3, period, { name: 'Calibri', size: 10.5, color: { argb: MUTED } });
  put(4, `Generated by ${generatedBy}  ·  ${formatDateTime(generatedAt)}`, { name: 'Calibri', size: 9, color: { argb: MUTED } });
  let r = 6;

  // ---- Summary block
  summary.slice(0, 8).forEach((s) => {
    ws.getCell(r, 1).value = s.label;
    ws.getCell(r, 1).font = { name: 'Calibri', size: 10, color: { argb: MUTED } };
    const v = ws.getCell(r, 2);
    v.value = s.type === 'date' || s.type === 'datetime' ? toManilaWallClock(toDate(s.value)) : s.value;
    if (NUM_FMT[s.type]) v.numFmt = NUM_FMT[s.type];
    v.font = { name: 'Calibri', size: 11, bold: true, color: { argb: NAVY } };
    v.alignment = { horizontal: 'left' };
    r += 1;
  });
  if (summary.length) r += 1;

  // ---- Table header
  const headerRow = r;
  columns.forEach((col, i) => {
    const c = ws.getCell(headerRow, i + 1);
    c.value = col.label;
    c.font = { name: 'Calibri', size: 11, bold: true, color: { argb: 'FFFFFFFF' } };
    c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
    c.alignment = { vertical: 'middle', horizontal: isNumericType(col.type) ? 'right' : 'left', indent: 1 };
  });
  ws.getRow(headerRow).height = 24;

  // ---- Data rows (real dates and numbers, not text)
  const widths = columns.map((c) => c.label.length + 4);
  const cellValue = (col, v) => {
    if (v === null || v === undefined || v === '') return null;
    if (col.type === 'date') { // calendar day only (no hidden time-of-day), so sorting and filtering by date work
      const d = toDate(v);
      if (!d) return null;
      const m = toManilaWallClock(d);
      return new Date(Date.UTC(m.getUTCFullYear(), m.getUTCMonth(), m.getUTCDate()));
    }
    if (col.type === 'datetime' || col.type === 'time') {
      const d = toDate(v);
      return d ? toManilaWallClock(d) : null;
    }
    if (isNumericType(col.type)) return Number(v);
    return String(v);
  };
  const writeRow = (rowIdx, values, { fill, bold, top }) => {
    columns.forEach((col, i) => {
      const c = ws.getCell(rowIdx, i + 1);
      c.value = values[i];
      if (NUM_FMT[col.type]) c.numFmt = NUM_FMT[col.type];
      c.font = { name: 'Calibri', size: 11, bold: !!bold, color: { argb: NAVY } };
      c.alignment = { vertical: 'middle', horizontal: isNumericType(col.type) ? 'right' : 'left', indent: 1 };
      c.border = { bottom: { style: 'thin', color: { argb: LINE } }, ...(top ? { top: { style: 'medium', color: { argb: NAVY } } } : {}) };
      if (fill) c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: fill } };
      const len = col.type === 'money' ? 14 : col.type === 'datetime' ? 24 : col.type === 'date' ? 14 : col.type === 'time' ? 10
        : String(values[i] ?? '').length + 3;
      widths[i] = Math.max(widths[i], len);
    });
    ws.getRow(rowIdx).height = 20;
  };

  rows.forEach((row, idx) => {
    writeRow(headerRow + 1 + idx, columns.map((c) => cellValue(c, row[c.key])), { fill: idx % 2 === 1 ? ZEBRA : null });
  });
  let end = headerRow + rows.length;
  if (!rows.length) {
    ws.mergeCells(headerRow + 1, 1, headerRow + 1, Math.max(last, 2));
    const c = ws.getCell(headerRow + 1, 1);
    c.value = 'No records for this period.';
    c.font = { name: 'Calibri', size: 11, italic: true, color: { argb: MUTED } };
    c.alignment = { horizontal: 'center', vertical: 'middle' };
    ws.getRow(headerRow + 1).height = 30;
    end = headerRow + 1;
  } else if (totals) {
    end += 1;
    writeRow(end, columns.map((c, i) => (totals.values?.[c.key] !== undefined ? Number(totals.values[c.key]) : i === 0 ? totals.label || 'Total' : null)),
      { fill: TOTALS, bold: true, top: true });
  }

  // ---- Column widths, freeze header, filter, repeat header when printing
  columns.forEach((_, i) => { ws.getColumn(i + 1).width = Math.min(Math.max(widths[i], 11), 42); });
  if (summary.length) ws.getColumn(1).width = Math.max(ws.getColumn(1).width, 24);
  ws.views = [{ state: 'frozen', ySplit: headerRow, showGridLines: false }];
  if (rows.length) ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow + rows.length, column: last } };
  ws.pageSetup.printTitlesRow = `${headerRow}:${headerRow}`;
  ws.pageSetup.printArea = `A1:${ws.getColumn(last).letter}${end}`;

  return Buffer.from(await wb.xlsx.writeBuffer());
}
